BY_NUMBER={d[0]:d for d in DOCUMENTS}

def source_path(number):
    n,title,group,*_=BY_NUMBER[number]
    return f'documents/{GROUPS[group]}/{n}_{title}.md'

def render_document(doc):
    n,title,group,code,version,start,end,sections=doc
    lines=[f'# {title}','','星海科技有限公司','',f'归口部门：{group}；入库范围：{group}。','',f'文档编号：{code}；版本：{version}；生效日期：{start}；状态：'+('历史归档。' if end else '现行。')]
    if end:lines.append(f'失效日期：{end}；适用期间：{start}至{end}。')
    for i,(heading,body) in enumerate(sections,1):lines += ['',f'## {i} {heading}','',body]
    return '\n'.join(lines)+'\n'

def evidence(n,text):return {'document':Path(source_path(n)).name,'text':text}

